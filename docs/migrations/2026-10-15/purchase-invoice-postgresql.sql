-- Container invoices, payments paid in several transfers, inspection paid through the supplier.
-- A container gets invoices of its own (number, date, amount, the file): every payment term of the payee
-- points at the payee's only invoice, or at the one a payment names (invoice_id; null means automatic).
-- One payment row stays one bank transfer: a payment paid in parts becomes a group of rows that share
-- group_id (the id of the payment that was split). The container's inspection_via_supplier says the
-- inspection travels in the goods' transfer.
-- Additive and rerunnable: one new table, nullable columns and their indexes. No foreign key (the service
-- clears what points at a deleted invoice), no check, no backfill: existing payments stay as they are.
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '60s';

create table if not exists purchase_invoice (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    payee varchar(16) not null,
    number varchar(64) not null,
    invoice_date date not null,
    amount numeric(19,2) not null,
    currency varchar(8) not null,
    amount_eur numeric(19,2) not null,
    document_id bigint,
    notes varchar(500),
    actor varchar(255),
    recorded_at timestamp(6) with time zone not null
);
create index if not exists ix_purchase_invoice_order on purchase_invoice(order_id);
create unique index if not exists uq_purchase_invoice_document on purchase_invoice(document_id);
alter table purchase_payment add column if not exists group_id bigint;
alter table purchase_payment add column if not exists invoice_id bigint;
create index if not exists ix_purchase_payment_group on purchase_payment(group_id);
create index if not exists ix_purchase_payment_invoice on purchase_payment(invoice_id);
alter table purchase_order add column if not exists inspection_via_supplier boolean;

COMMIT;
