BEGIN;
CREATE TABLE IF NOT EXISTS product_channel_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL,
    channel varchar(30) NOT NULL,
    manual_price numeric(19,4), manual_unit varchar(30),
    observed_price numeric(19,4), observed_unit varchar(30), observed_at timestamp,
    observed_sale_id bigint, updated_at timestamptz NOT NULL,
    CONSTRAINT uk_product_channel_price UNIQUE(product_id, channel)
);
CREATE TABLE IF NOT EXISTS product_channel_price_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL, channel varchar(30) NOT NULL,
    price_excl_vat numeric(19,4), unit varchar(30), source varchar(30), source_sale_id bigint,
    changed_at timestamptz NOT NULL, changed_by varchar(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_channel_price_history
    ON product_channel_price_history(product_id, channel, changed_at);
COMMIT;
