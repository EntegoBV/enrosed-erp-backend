                (media_asset_id is null and media_version_id is null)
                or (media_asset_id is not null and media_version_id is not null));
    end if;
    if not exists (select 1 from pg_constraint
            where conrelid = 'sales_document_media_snapshot'::regclass
            and conname = 'fk_sales_document_media_version') then
