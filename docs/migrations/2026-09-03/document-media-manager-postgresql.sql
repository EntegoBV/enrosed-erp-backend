    if to_regclass('sales_order') is not null and not exists (
            select 1 from pg_constraint
            where conrelid = 'sales_document_media_snapshot'::regclass
            and conname = 'fk_sales_document_media_order') then
        alter table sales_document_media_snapshot add constraint fk_sales_document_media_order
            foreign key (order_id) references sales_order(id) on delete cascade;
    end if;
    if to_regclass('product') is not null and not exists (
            select 1 from pg_constraint
            where conrelid = 'sales_document_media_snapshot'::regclass
            and conname = 'fk_sales_document_media_product') then
        alter table sales_document_media_snapshot add constraint fk_sales_document_media_product
            foreign key (product_id) references product(id) on delete restrict;
