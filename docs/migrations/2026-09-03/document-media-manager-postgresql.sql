-- Central document and media registry. Additive only: legacy file tables and blobs remain intact.
-- IF NOT EXISTS keeps this safe when a schema was prepared manually; the script is rerunnable.

create table if not exists media_asset (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    kind varchar(20) not null,
    current_version_id bigint,
    archived boolean not null default false,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    created_by varchar(64),
    constraint ck_media_asset_kind check (kind in ('IMAGE', 'DOCUMENT'))
);

create table if not exists media_version (
    id bigint generated by default as identity primary key,
    asset_id bigint not null,
    version_number integer not null,
    storage_key varchar(80) not null,
    original_filename varchar(255) not null,
    content_type varchar(120) not null,
    size_bytes bigint not null,
    sha256 varchar(64) not null,
    width_px integer,
    height_px integer,
    thumbnail_storage_key varchar(80),
    thumbnail_content_type varchar(120),
    thumbnail_size_bytes bigint,
    thumbnail_width_px integer,
    thumbnail_height_px integer,
    created_at timestamp with time zone not null,
    created_by varchar(64),
    constraint fk_media_version_asset foreign key (asset_id) references media_asset(id) on delete cascade,
    constraint uk_media_version_asset_number unique (asset_id, version_number),
    constraint uk_media_version_sha256 unique (sha256),
    constraint uk_media_version_id_asset unique (id, asset_id),
    constraint ck_media_version_number check (version_number > 0),
    constraint ck_media_version_size check (size_bytes >= 0)
);

create table if not exists media_link (
    id bigint generated by default as identity primary key,
    asset_id bigint not null,
    target_type varchar(30) not null,
    target_id bigint not null,
    role varchar(20) not null,
    primary_slot integer,
    pinned_version_id bigint,
    legacy_only boolean not null default false,
    created_at timestamp with time zone not null,
    created_by varchar(64),
    constraint fk_media_link_asset foreign key (asset_id) references media_asset(id) on delete cascade,
    constraint fk_media_link_pinned_version foreign key (pinned_version_id, asset_id)
        references media_version(id, asset_id),
    constraint uk_media_link_asset_target_role unique (asset_id, target_type, target_id, role),
    constraint ck_media_link_target_type check (
        target_type in ('PRODUCT', 'PRODUCT_FAMILY', 'PURCHASE_ORDER', 'PLANNER_ITEM')),
    constraint ck_media_link_role check (role in ('CATALOGUE', 'QUOTE', 'INVOICE', 'INTERNAL')),
    constraint ck_media_link_primary_slot check (primary_slot is null or primary_slot = 1)
);

create table if not exists media_legacy_source (
    id bigint generated by default as identity primary key,
    source_type varchar(30) not null,
    source_id bigint not null,
    asset_id bigint not null,
    version_id bigint not null,
    target_type varchar(30) not null,
    target_id bigint not null,
    role varchar(20) not null,
    label varchar(255),
    indexed_at timestamp with time zone not null,
    constraint fk_media_legacy_source_asset foreign key (asset_id) references media_asset(id) on delete cascade,
    constraint fk_media_legacy_source_version foreign key (version_id, asset_id)
        references media_version(id, asset_id),
    constraint uk_media_legacy_source_identity unique (source_type, source_id),
    constraint ck_media_legacy_source_type check (
        source_type in ('PRODUCT_PHOTO', 'FAMILY_PHOTO', 'PURCHASE_DOCUMENT', 'PLANNER_ATTACHMENT')),
    constraint ck_media_legacy_target_type check (
        target_type in ('PRODUCT', 'PRODUCT_FAMILY', 'PURCHASE_ORDER', 'PLANNER_ITEM')),
    constraint ck_media_legacy_role check (role in ('CATALOGUE', 'QUOTE', 'INVOICE', 'INTERNAL'))
);

create table if not exists sales_document_media_snapshot (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    product_id bigint not null,
    role varchar(20) not null,
    storage_key varchar(80) not null,
    content_type varchar(120) not null,
    original_filename varchar(255) not null,
    media_asset_id bigint,
    media_version_id bigint,
    created_at timestamp with time zone not null,
    constraint uk_sales_document_media_snapshot unique (order_id, product_id, role),
    constraint ck_sales_document_media_role check (role in ('QUOTE', 'INVOICE'))
);

