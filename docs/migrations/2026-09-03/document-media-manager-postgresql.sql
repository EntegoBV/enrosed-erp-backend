            unique (asset_id, version_number);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_version'::regclass
            and conname = 'uk_media_version_sha256') then
        alter table media_version add constraint uk_media_version_sha256 unique (sha256);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_version'::regclass
            and conname = 'uk_media_version_id_asset') then
        alter table media_version add constraint uk_media_version_id_asset unique (id, asset_id);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_version'::regclass
            and conname = 'ck_media_version_number') then
        alter table media_version add constraint ck_media_version_number check (version_number > 0);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_version'::regclass
            and conname = 'ck_media_version_size') then
        alter table media_version add constraint ck_media_version_size check (size_bytes >= 0);
    end if;
    if to_regclass('photo_blob') is not null and not exists (
            select 1 from pg_constraint where conrelid = 'media_version'::regclass
            and conname = 'fk_media_version_storage_blob') then
        alter table media_version add constraint fk_media_version_storage_blob
            foreign key (storage_key) references photo_blob(storageKey) on delete restrict;
    end if;
    if to_regclass('photo_blob') is not null and not exists (
            select 1 from pg_constraint where conrelid = 'media_version'::regclass
            and conname = 'fk_media_version_thumbnail_blob') then
        alter table media_version add constraint fk_media_version_thumbnail_blob
            foreign key (thumbnail_storage_key) references photo_blob(storageKey) on delete restrict;
    end if;

    if not exists (select 1 from pg_constraint where conrelid = 'media_link'::regclass
            and conname = 'fk_media_link_asset') then
        alter table media_link add constraint fk_media_link_asset
            foreign key (asset_id) references media_asset(id) on delete cascade;
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_link'::regclass
            and conname = 'fk_media_link_pinned_version') then
        alter table media_link add constraint fk_media_link_pinned_version
            foreign key (pinned_version_id, asset_id) references media_version(id, asset_id);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_link'::regclass
            and conname = 'uk_media_link_asset_target_role') then
        alter table media_link add constraint uk_media_link_asset_target_role
            unique (asset_id, target_type, target_id, role);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_link'::regclass
            and conname = 'ck_media_link_target_type') then
        alter table media_link add constraint ck_media_link_target_type check (
            target_type in ('PRODUCT', 'PRODUCT_FAMILY', 'PURCHASE_ORDER', 'PLANNER_ITEM'));
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_link'::regclass
            and conname = 'ck_media_link_role') then
        alter table media_link add constraint ck_media_link_role
            check (role in ('CATALOGUE', 'QUOTE', 'INVOICE', 'INTERNAL'));
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_link'::regclass
            and conname = 'ck_media_link_primary_slot') then
        alter table media_link add constraint ck_media_link_primary_slot
            check (primary_slot is null or primary_slot = 1);
    end if;

    if not exists (select 1 from pg_constraint where conrelid = 'media_legacy_source'::regclass
            and conname = 'fk_media_legacy_source_asset') then
        alter table media_legacy_source add constraint fk_media_legacy_source_asset
            foreign key (asset_id) references media_asset(id) on delete cascade;
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_legacy_source'::regclass
            and conname = 'fk_media_legacy_source_version') then
        alter table media_legacy_source add constraint fk_media_legacy_source_version
            foreign key (version_id, asset_id) references media_version(id, asset_id);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_legacy_source'::regclass
            and conname = 'uk_media_legacy_source_identity') then
        alter table media_legacy_source add constraint uk_media_legacy_source_identity
            unique (source_type, source_id);
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_legacy_source'::regclass
            and conname = 'ck_media_legacy_source_type') then
        alter table media_legacy_source add constraint ck_media_legacy_source_type check (
            source_type in ('PRODUCT_PHOTO', 'FAMILY_PHOTO', 'PURCHASE_DOCUMENT', 'PLANNER_ATTACHMENT'));
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_legacy_source'::regclass
            and conname = 'ck_media_legacy_target_type') then
        alter table media_legacy_source add constraint ck_media_legacy_target_type check (
            target_type in ('PRODUCT', 'PRODUCT_FAMILY', 'PURCHASE_ORDER', 'PLANNER_ITEM'));
    end if;
    if not exists (select 1 from pg_constraint where conrelid = 'media_legacy_source'::regclass
            and conname = 'ck_media_legacy_role') then
        alter table media_legacy_source add constraint ck_media_legacy_role
            check (role in ('CATALOGUE', 'QUOTE', 'INVOICE', 'INTERNAL'));
