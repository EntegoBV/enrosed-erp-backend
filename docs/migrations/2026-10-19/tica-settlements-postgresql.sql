BEGIN;
CREATE TABLE IF NOT EXISTS tica_settlement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference varchar(120) NOT NULL UNIQUE, source_key varchar(300) UNIQUE, location varchar(160) NOT NULL,
    document_date date NOT NULL, due_date date NOT NULL, period_from date NOT NULL, period_to date NOT NULL,
    sales_excl numeric(15,2) NOT NULL, sales_vat numeric(15,2) NOT NULL,
    commission_excl numeric(15,2) NOT NULL, commission_vat numeric(15,2) NOT NULL,
    net_receivable numeric(15,2) NOT NULL, document_note varchar(2000), source_document_url varchar(2000),
    status varchar(20) NOT NULL DEFAULT 'DRAFT',
    commission_cost_id bigint UNIQUE, commission_payment_id bigint UNIQUE,
    bank_statement_line_id bigint UNIQUE, paid_at timestamptz,
    created_at timestamptz NOT NULL, confirmed_at timestamptz
);
ALTER TABLE bank_statement_line ADD COLUMN IF NOT EXISTS tica_settlement_id bigint;
ALTER TABLE bank_statement_line ADD COLUMN IF NOT EXISTS tica_settlement_amount_eur numeric(19,2);
ALTER TABLE cost_payment ADD COLUMN IF NOT EXISTS settlement_offset boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS uk_bank_tica_settlement ON bank_statement_line (tica_settlement_id) WHERE tica_settlement_id IS NOT NULL;
COMMIT;
