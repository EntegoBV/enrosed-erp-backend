BEGIN;

CREATE TABLE IF NOT EXISTS tica_settings (
    id bigint PRIMARY KEY CHECK (id = 1),
    notification_mode varchar(30) NOT NULL DEFAULT 'DAILY',
    summary_time varchar(5) NOT NULL DEFAULT '21:00',
    sync_requested boolean NOT NULL DEFAULT false,
    lease_token varchar(40), lease_until timestamptz,
    last_attempt_at timestamptz, last_success_at timestamptz,
    last_range_from date, last_range_to date, coverage_from date, coverage_to date, last_error varchar(500)
);
INSERT INTO tica_settings (id, notification_mode, summary_time, sync_requested)
VALUES (1, 'DAILY', '21:00', false) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS tica_sale (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location varchar(160) NOT NULL, exhibitor varchar(30) NOT NULL,
    sold_at timestamp NOT NULL, transaction_number varchar(80) NOT NULL, line_number varchar(80) NOT NULL,
    description varchar(1000) NOT NULL, beeyond_article_number varchar(100), sku varchar(150), barcode varchar(100),
    quantity numeric(15,3) NOT NULL, discount_percent numeric(6,2) NOT NULL,
    gross_total numeric(15,2) NOT NULL, net_total numeric(15,2) NOT NULL, vat_rate numeric(6,2),
    transaction_type varchar(100) NOT NULL, product_id bigint, active boolean NOT NULL DEFAULT true,
    first_seen_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
    CONSTRAINT uk_tica_source_line UNIQUE (exhibitor, location, transaction_number, line_number)
);
CREATE INDEX IF NOT EXISTS idx_tica_sale_date ON tica_sale (sold_at);

CREATE TABLE IF NOT EXISTS tica_notice (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_key varchar(400) NOT NULL, kind varchar(20) NOT NULL,
    title varchar(120) NOT NULL, body varchar(500) NOT NULL, status varchar(30) NOT NULL DEFAULT 'PENDING',
    created_at timestamptz NOT NULL, expires_at timestamptz NOT NULL, next_attempt_at timestamptz NOT NULL,
    accepted_at timestamptz, attempt_count integer NOT NULL DEFAULT 0, lease_token varchar(40),
    CONSTRAINT uk_tica_notice_key UNIQUE (notice_key)
);
CREATE TABLE IF NOT EXISTS tica_delivery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id bigint NOT NULL, subscription_id bigint NOT NULL, accepted_at timestamptz, last_status integer,
    attempt_count integer NOT NULL DEFAULT 0,
    CONSTRAINT uk_tica_notice_device UNIQUE (notice_id, subscription_id)
);
ALTER TABLE tica_delivery ADD COLUMN IF NOT EXISTS attempt_count integer NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS idx_tica_notice_due ON tica_notice (status, next_attempt_at);
COMMIT;
