-- Additive notice and per-device acknowledgement storage; no purchasing or finance mutation.
create table if not exists container_arrival_notice (
    id varchar(64) primary key,
    order_id bigint not null,
    reference_hash varchar(64) not null,
    threshold_days integer not null,
    expected_arrival date not null,
    title varchar(300) not null,
    body varchar(1000) not null,
    status varchar(30) not null,
    created_at timestamptz not null,
    next_attempt_at timestamptz not null,
    accepted_at timestamptz,
    lease_token varchar(40)
);
create index if not exists ix_container_arrival_dispatch on container_arrival_notice(status, next_attempt_at);
create index if not exists ix_container_arrival_order on container_arrival_notice(order_id);
create table if not exists container_arrival_delivery (
    id bigint generated by default as identity primary key,
    notice_id varchar(64) not null,
    subscription_id bigint not null,
    attempt_count integer not null default 0,
    last_status integer,
    accepted_at timestamptz,
    unique(notice_id, subscription_id)
);
