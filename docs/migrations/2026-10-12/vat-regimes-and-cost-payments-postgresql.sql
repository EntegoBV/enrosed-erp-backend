-- The VAT regime, deductibility and depreciation of a cost (company_cost and
-- recurring_cost), the country, VAT number and regime of a party (cost_party),
-- the clearance of a container (purchase_order), the ET 14000 setting
-- (company_profile) and the payments on a cost (cost_payment).
-- Additive and rerunnable: nullable columns, a table created when missing, no
-- foreign key (the service deletes the payments before the cost, so dev H2 and
-- PostgreSQL behave the same), and two backfills that run once.
-- The regime backfill is statistical: a cost with a VAT rate above zero is read
-- as a Belgian invoice (vat_regime = 'BE'), unconfirmed, so the screen asks to
-- confirm it; a cost at 0 % or without a rate stays unknown (null) and is listed
-- under "Nog te bepalen" in the return. Every cost that was paid gets one
-- payment row for its cash total on its "Betaald op", carrying the bank link.
BEGIN;

alter table company_cost add column if not exists vat_regime varchar(24);
alter table company_cost add column if not exists vat_regime_confirmed boolean;
alter table company_cost add column if not exists supplier_country varchar(2);
alter table company_cost add column if not exists cost_kind varchar(16);
alter table company_cost add column if not exists expense_type varchar(24);
alter table company_cost add column if not exists vat_deductible_pct numeric(5,2);
alter table company_cost add column if not exists tax_deductible_pct numeric(5,2);
alter table company_cost add column if not exists depreciation_years integer;
alter table company_cost add column if not exists depreciation_start date;

alter table recurring_cost add column if not exists vat_regime varchar(24);
alter table recurring_cost add column if not exists vat_regime_confirmed boolean;
alter table recurring_cost add column if not exists supplier_country varchar(2);
alter table recurring_cost add column if not exists cost_kind varchar(16);
alter table recurring_cost add column if not exists expense_type varchar(24);
alter table recurring_cost add column if not exists vat_deductible_pct numeric(5,2);
alter table recurring_cost add column if not exists tax_deductible_pct numeric(5,2);

alter table cost_party add column if not exists country varchar(2);
alter table cost_party add column if not exists vat_number varchar(20);
alter table cost_party add column if not exists vat_regime varchar(24);

alter table purchase_order add column if not exists clearance varchar(24);

alter table company_profile add column if not exists import_vat_deferred boolean;

create table if not exists cost_payment (
    id bigint generated by default as identity primary key,
    company_cost_id bigint not null,
    paid_on date not null,
    amount_eur numeric(19,2) not null,
    account varchar(120),
    bank_statement_line_id bigint,
    note varchar(300),
    recorded_at timestamp(6) with time zone not null,
    actor varchar(255)
);

create index if not exists ix_cost_payment_cost on cost_payment(company_cost_id);
create index if not exists ix_cost_payment_bank_line on cost_payment(bank_statement_line_id);

-- A Belgian rate means a Belgian invoice, until someone confirms or changes it.
update company_cost set vat_regime = 'BE', vat_regime_confirmed = false where vat_regime is null and vat_pct > 0;
update recurring_cost set vat_regime = 'BE', vat_regime_confirmed = false where vat_regime is null and vat_pct > 0;

-- Every paid cost without payment rows gets the one payment "Betaald op" stood for.
insert into cost_payment (company_cost_id, paid_on, amount_eur, bank_statement_line_id, note, recorded_at, actor)
select c.id, c.paid_on, coalesce(c.amount_incl_eur, round(c.amount_excl_eur * (1 + coalesce(c.vat_pct, 0) / 100), 2)),
       c.bank_statement_line_id, 'Overgenomen uit Betaald op', now(), 'migratie'
from company_cost c
where c.paid_on is not null and not exists (select 1 from cost_payment p where p.company_cost_id = c.id);

COMMIT;
