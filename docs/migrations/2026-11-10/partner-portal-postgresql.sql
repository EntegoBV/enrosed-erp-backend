-- Partnerportaal (Emre, 2026-11-10): the partner Verhoeven logs in with a login of its own
-- (role partner, never admin), reports what sold at the auction or directly and what it bought
-- back on the clock; staff invoice those meldingen (Veilingverkopen) whenever they want.
--
-- partner_login            one login per partner customer; username lower case, bcrypt hash only
-- partner_session          server-side sessions of that login (epp1_ tokens, only the SHA-256 kept)
-- partner_portal_settings  per partner: auction commission and transport percent (null = 4.50 and
--                          5.50) and the stock location (null = MAIN); the row is also the lock that
--                          serialises meldingen, voids and invoicing of one partner
-- partner_sale_report      one melding (VV-<id>): channel, sold_on, the cost percents as they stood
-- partner_sale_report_line one row per part: an entry split over its sources (a partner container or
--                          own stock), SALE or BUYBACK, with its money and the stock movement it booked
-- partner_sale_invoice_part append-only: which part went on which sales document; a document with
--                          rows here is report-backed, also after a trash or a new run
--
-- Additive and rerunnable: six new tables with named constraints and indexes, no existing table is
-- touched and no row is written. Every column carries the name its entity gives it, every non-id
-- column is nullable (integrity lives in the services, no foreign keys), kinds and channels are
-- plain varchars without a CHECK constraint, money is numeric(19,2), unit prices numeric(19,4),
-- percents numeric(7,4). Runs after customer-crm-status-touchpoints-postgresql.sql.
begin;
set local lock_timeout = '15s';

create table if not exists partner_login (
    id bigint generated by default as identity primary key,
    customer_id bigint,
    username varchar(64),
    display_name varchar(100),
    password_hash varchar(100),
    active boolean,
    password_set_at timestamptz,
    last_login_at timestamptz,
    created_at timestamptz,
    created_by varchar(64),
    updated_at timestamptz,
    updated_by varchar(64),
    constraint uq_partner_login_customer unique (customer_id),
    constraint uq_partner_login_username unique (username)
);

create table if not exists partner_session (
    id bigint generated by default as identity primary key,
    login_id bigint,
    token_hash varchar(64),
    created_at timestamptz,
    last_seen_at timestamptz,
    expires_at timestamptz,
    constraint uq_partner_session_token_hash unique (token_hash)
);
create index if not exists idx_partner_session_login on partner_session (login_id);

create table if not exists partner_portal_settings (
    customer_id bigint primary key,
    auction_commission_pct numeric(7,4),
    auction_transport_pct numeric(7,4),
    location_id bigint,
    updated_at timestamptz,
    updated_by varchar(64)
);

create table if not exists partner_sale_report (
    id bigint generated by default as identity primary key,
    customer_id bigint,
    login_id bigint,
    channel varchar(20),
    sold_on date,
    commission_pct numeric(7,4),
    transport_pct numeric(7,4),
    extra_cost_mode varchar(10),
    extra_cost_value numeric(19,4),
    note varchar(500),
    location_id bigint,
    client_ref varchar(64),
    created_at timestamptz,
    created_by varchar(64),
    created_by_name varchar(100),
    voided_at timestamptz,
    voided_by varchar(64),
    void_reason varchar(200),
    constraint uq_partner_sale_report_client_ref unique (customer_id, client_ref)
);
create index if not exists idx_partner_sale_report_customer on partner_sale_report (customer_id, id);
create index if not exists idx_partner_sale_report_sold_on on partner_sale_report (sold_on);

create table if not exists partner_sale_report_line (
    id bigint generated by default as identity primary key,
    report_id bigint,
    customer_id bigint,
    product_id bigint,
    entry_no integer,
    line_type varchar(10),
    purchase_order_id bigint,
    quantity integer,
    unit_price_eur numeric(19,4),
    gross_eur numeric(19,2),
    commission_eur numeric(19,2),
    transport_eur numeric(19,2),
    extra_cost_eur numeric(19,2),
    net_eur numeric(19,2),
    unit_cost_eur numeric(19,4),
    unit_cost_estimated boolean,
    mirrors_line_id bigint,
    stock_movement_id bigint,
    invoice_id bigint,
    invoiced_at timestamptz
);
-- unit_cost_estimated: some pieces of an own part had no known cost and count at the average of the known ones
alter table partner_sale_report_line add column if not exists unit_cost_estimated boolean;
create index if not exists idx_partner_sale_line_report on partner_sale_report_line (report_id);
create index if not exists idx_partner_sale_line_customer_invoice on partner_sale_report_line (customer_id, invoice_id);
create index if not exists idx_partner_sale_line_container on partner_sale_report_line (purchase_order_id, product_id);
create index if not exists idx_partner_sale_line_invoice on partner_sale_report_line (invoice_id);
create index if not exists idx_partner_sale_line_mirrors on partner_sale_report_line (mirrors_line_id);

create table if not exists partner_sale_invoice_part (
    id bigint generated by default as identity primary key,
    sales_order_id bigint,
    line_id bigint,
    quantity integer,
    created_at timestamptz
);
create index if not exists idx_partner_sale_invoice_part_order on partner_sale_invoice_part (sales_order_id);
create index if not exists idx_partner_sale_invoice_part_line on partner_sale_invoice_part (line_id);

commit;
