-- Partnerportaal, round 2 (Emre, 2026-11-12): Frans counts per roos / bowl / display / omdoos,
-- a melding holds extra cost lines with a description, a buyback carries commission and transport,
-- meldingen stay editable until staff confirm them, a direct sale names its buyer (an ERP customer
-- Frans picked or added), and Factureren keeps the figures it invoiced per document and product.
--
-- partner_sale_report        + confirmed_at/by/by_name (staff confirmed it), updated_at/by/by_name (last
--                              edit), revision_of (set on an archive row: the old lines of an edited melding,
--                              never listed), buyer_customer_id (the buyer of a direct sale)
-- partner_sale_report_line   + entered_unit (STUK | VERPAKKING | OMDOOS), entered_count, piece_price_eur and
--                              entered_pieces_per_unit: what was typed, per side (sale rows and buyback rows
--                              each carry their own); quantity stays in sales units
-- partner_sale_report_cost   the extra cost lines of a melding (0..5): description, cost_mode AMOUNT | PCT,
--                              cost_value (VALUE is reserved in H2, hence the prefix)
-- partner_product_unit       per partner and product the count unit staff set as default (no row = STUK)
-- partner_customer_link      which ERP customers a partner picked or added as a buyer; reviewed_* once staff
--                              checked a customer the partner added
-- partner_sale_invoice_figure per document and product the figures Factureren invoiced (preview, note and
--                              the margin popup read them; documents from before round 2 have none)
--
-- Additive and rerunnable: new nullable columns and four new tables with named constraints and
-- indexes, no row is written or changed (open round-1 meldingen show as "Te bevestigen" until staff
-- confirm them). Every column carries the name its entity gives it, no foreign keys, kinds as plain
-- varchar, money numeric(19,2), unit and piece prices numeric(19,4), percents numeric(7,4).
-- Runs after 2026-11-10/partner-portal-postgresql.sql.
begin;
set local lock_timeout = '15s';

alter table partner_sale_report add column if not exists confirmed_at timestamptz;
alter table partner_sale_report add column if not exists confirmed_by varchar(64);
alter table partner_sale_report add column if not exists confirmed_by_name varchar(100);
alter table partner_sale_report add column if not exists updated_at timestamptz;
alter table partner_sale_report add column if not exists updated_by varchar(64);
alter table partner_sale_report add column if not exists updated_by_name varchar(100);
alter table partner_sale_report add column if not exists revision_of bigint;
alter table partner_sale_report add column if not exists buyer_customer_id bigint;
create index if not exists idx_partner_sale_report_revision_of on partner_sale_report (revision_of);
create index if not exists idx_partner_sale_report_buyer on partner_sale_report (buyer_customer_id);

alter table partner_sale_report_line add column if not exists entered_unit varchar(12);
alter table partner_sale_report_line add column if not exists entered_count integer;
alter table partner_sale_report_line add column if not exists piece_price_eur numeric(19,4);
alter table partner_sale_report_line add column if not exists entered_pieces_per_unit integer;

create table if not exists partner_sale_report_cost (
    id bigint generated by default as identity primary key,
    report_id bigint,
    line_no integer,
    description varchar(80),
    cost_mode varchar(10),
    cost_value numeric(19,4)
);
create index if not exists idx_partner_sale_report_cost_report on partner_sale_report_cost (report_id);

create table if not exists partner_product_unit (
    id bigint generated by default as identity primary key,
    customer_id bigint,
    product_id bigint,
    unit varchar(12),
    updated_at timestamptz,
    updated_by varchar(64),
    constraint uq_partner_product_unit unique (customer_id, product_id)
);

create table if not exists partner_customer_link (
    id bigint generated by default as identity primary key,
    partner_customer_id bigint,
    customer_id bigint,
    added_by_partner boolean,
    login_id bigint,
    created_at timestamptz,
    created_by varchar(64),
    created_by_name varchar(100),
    reviewed_at timestamptz,
    reviewed_by varchar(64),
    constraint uq_partner_customer_link unique (partner_customer_id, customer_id)
);
create index if not exists idx_partner_customer_link_customer on partner_customer_link (customer_id);

create table if not exists partner_sale_invoice_figure (
    id bigint generated by default as identity primary key,
    sales_order_id bigint,
    product_id bigint,
    sold_quantity integer,
    bought_back_quantity integer,
    quantity integer,
    sale_pieces integer,
    gross_eur numeric(19,2),
    commission_eur numeric(19,2),
    transport_eur numeric(19,2),
    extra_eur numeric(19,2),
    buyback_cost_eur numeric(19,2),
    proceeds_eur numeric(19,2),
    absorbed_eur numeric(19,2),
    cost_eur numeric(19,2),
    value_eur numeric(19,2),
    advance_eur numeric(19,2),
    correction_eur numeric(19,2),
    profit_share_pct numeric(7,4),
    cost_share_pct numeric(7,4),
    report_ids varchar(500),
    created_at timestamptz
);
create index if not exists idx_partner_sale_invoice_figure_order on partner_sale_invoice_figure (sales_order_id);

commit;
