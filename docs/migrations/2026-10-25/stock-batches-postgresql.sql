-- Stock batches: which container's pieces are still on the shelf and at what cost; additive only.
begin;
set local lock_timeout = '10s';
set local statement_timeout = '60s';

create table if not exists stock_batch (
    id bigint generated by default as identity primary key,
    product_id bigint,
    kind varchar(16),
    owner varchar(16),
    purchase_order_id bigint,
    purchase_order_line_id bigint,
    order_number varchar(120),
    supplier_id bigint,
    product_supplier_id bigint,
    received_on date,
    booked_at timestamptz,
    unit_pieces integer,
    pieces_in integer,
    pieces_left integer,
    cost_state varchar(16),
    unit_cost_eur numeric(19,4),
    unit_cost_excl_enrosed_eur numeric(19,4),
    goods_eur numeric(19,4),
    origin_eur numeric(19,4),
    freight_eur numeric(19,4),
    duty_eur numeric(19,4),
    destination_eur numeric(19,4),
    enrosed_eur numeric(19,4),
    separate_eur numeric(19,4),
    cost_applied_at timestamptz,
    cost_applied_by varchar(80),
    note varchar(300),
    created_at timestamptz,
    created_by varchar(80)
);
create unique index if not exists uq_stock_batch_po_line on stock_batch (purchase_order_line_id) where purchase_order_line_id is not null;
create index if not exists idx_stock_batch_product on stock_batch (product_id, received_on, id);
create index if not exists idx_stock_batch_po on stock_batch (purchase_order_id);

create table if not exists stock_batch_move (
    id bigint generated by default as identity primary key,
    batch_id bigint,
    product_id bigint,
    stock_movement_id bigint,
    link_move_id bigint,
    kind varchar(40),
    pieces integer,
    unit_pieces integer,
    unit_cost_eur numeric(19,4),
    unit_cost_excl_enrosed_eur numeric(19,4),
    sales_order_id bigint,
    tica_sale_id bigint,
    purchase_order_id bigint,
    pinned boolean,
    reference varchar(160),
    moved_at timestamptz,
    actor varchar(80)
);
create index if not exists idx_stock_batch_move_batch on stock_batch_move (batch_id, id);
create index if not exists idx_stock_batch_move_product on stock_batch_move (product_id, id);
create index if not exists idx_stock_batch_move_sale on stock_batch_move (sales_order_id);
create index if not exists idx_stock_batch_move_tica on stock_batch_move (tica_sale_id);
create index if not exists idx_stock_batch_move_link on stock_batch_move (link_move_id);

create table if not exists stock_batch_run (
    id bigint generated by default as identity primary key,
    ran_at timestamptz,
    ran_by varchar(80),
    products integer,
    batches integer,
    opening_pieces integer,
    unassigned_pieces integer,
    note varchar(500),
    paused_at timestamptz,
    paused_by varchar(80)
);

alter table sales_order_line add column if not exists stock_cost_eur numeric(19,4);
commit;
