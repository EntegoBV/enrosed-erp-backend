-- One product, several suppliers (Emre 2026-10-25: "een product kan door meerdere leveranciers gemaakt worden ...
-- versies"). One row per (product, supplier) with that supplier's own EXW price, reference, version label, MOQ,
-- lead time and agreement note. The product row keeps its supplier and purchase columns as a server-kept copy of
-- the preferred row. Purchase order lines name their row and freeze version, reference and the extra unit cost
-- when the order is placed.
-- Additive and rerunnable: one table, three nullable line columns, backfills that only fill what is still empty or
-- disagrees with the product card. No foreign key (product delete removes its rows in code), plain varchar instead
-- of enum checks.
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';

CREATE TABLE IF NOT EXISTS product_supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL,
    supplier_id bigint NOT NULL,
    preferred boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    version_label varchar(60),
    supplier_reference varchar(120),
    exw_price numeric(19,6),
    exw_currency varchar(3),
    extra_unit_cost numeric(19,6),
    moq integer,
    lead_time_days integer,
    supplier_note varchar(4000),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_product_supplier UNIQUE (product_id, supplier_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_supplier_preferred ON product_supplier (product_id) WHERE preferred;
CREATE INDEX IF NOT EXISTS idx_product_supplier_supplier ON product_supplier (supplier_id);

ALTER TABLE purchase_order_line ADD COLUMN IF NOT EXISTS product_supplier_id bigint;
ALTER TABLE purchase_order_line ADD COLUMN IF NOT EXISTS supplier_version_label varchar(60);
ALTER TABLE purchase_order_line ADD COLUMN IF NOT EXISTS supplier_reference varchar(120);
CREATE INDEX IF NOT EXISTS idx_purchase_order_line_product_supplier ON purchase_order_line (product_supplier_id);

-- 1a. A preferred row of another supplier than the product's own stops being preferred
--     (the old app changed the product's supplier after an earlier run).
UPDATE product_supplier s
   SET preferred = false, updated_at = now()
  FROM product p
 WHERE p.id = s.product_id AND s.preferred
   AND p.supplierid IS NOT NULL AND s.supplier_id <> p.supplierid;

-- 1b. An existing row of the product's own supplier becomes preferred and active, with the product card's values.
UPDATE product_supplier s
   SET preferred = true, active = true, exw_price = p.exwprice, exw_currency = p.exwcurrency,
       extra_unit_cost = p.extraunitcost, supplier_note = p.suppliernote, updated_at = now()
  FROM product p
 WHERE p.id = s.product_id AND s.supplier_id = p.supplierid AND NOT s.preferred
   AND NOT EXISTS (SELECT 1 FROM product_supplier x WHERE x.product_id = p.id AND x.preferred);

-- 1c. A product without a row of its own supplier gets it, preferred.
INSERT INTO product_supplier (product_id, supplier_id, preferred, active,
                              exw_price, exw_currency, extra_unit_cost, supplier_note, created_at, updated_at)
SELECT p.id, p.supplierid, true, true, p.exwprice, p.exwcurrency, p.extraunitcost, p.suppliernote, now(), now()
  FROM product p
 WHERE p.supplierid IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM product_supplier s WHERE s.product_id = p.id AND s.supplier_id = p.supplierid);

-- 1d. The preferred row carries what the product card shows (edits the old app made during the deploy).
UPDATE product_supplier s
   SET exw_price = p.exwprice, exw_currency = p.exwcurrency, extra_unit_cost = p.extraunitcost,
       supplier_note = p.suppliernote, updated_at = now()
  FROM product p
 WHERE p.id = s.product_id AND s.preferred AND s.supplier_id = p.supplierid
   AND (s.exw_price IS DISTINCT FROM p.exwprice OR s.exw_currency IS DISTINCT FROM p.exwcurrency
        OR s.extra_unit_cost IS DISTINCT FROM p.extraunitcost OR s.supplier_note IS DISTINCT FROM p.suppliernote);

-- 2. A supplier the product was bought from before it moved: an inactive row, priced as last ordered.
--    Only for products with a supplier of their own, so no product ends up with rows but no Voorkeur.
INSERT INTO product_supplier (product_id, supplier_id, preferred, active, exw_price, exw_currency, created_at, updated_at)
SELECT DISTINCT ON (l.productid, o.supplierid)
       l.productid, o.supplierid, false, false, l.exwprice, l.exwcurrency, now(), now()
  FROM purchase_order_line l
  JOIN purchase_order o ON o.id = l.order_id
  JOIN product p ON p.id = l.productid
 WHERE o.supplierid IS NOT NULL
   AND p.supplierid IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM product_supplier s
                    WHERE s.product_id = l.productid AND s.supplier_id = o.supplierid)
 ORDER BY l.productid, o.supplierid, (l.exwprice IS NULL), o.orderdate DESC NULLS LAST, o.id DESC;

-- 3. Every line names the row of its product at its container's supplier (trashed containers included).
UPDATE purchase_order_line l
   SET product_supplier_id = s.id
  FROM purchase_order o, product_supplier s
 WHERE o.id = l.order_id
   AND s.product_id = l.productid AND s.supplier_id = o.supplierid
   AND l.product_supplier_id IS NULL;

-- 4. Placed lines stop following the live product: what they calculate with today is frozen on the line. A line
--    follows the product card only while its container's supplier is the product's own or had no row before this run
--    (created_at = now() marks the rows this transaction made; on the first run that is every row, so every placed
--    line is frozen as the old app calculated it). A line priced from another supplier's row is left to that row.
UPDATE purchase_order_line l
   SET extraunitcost = coalesce(p.extraunitcost, 0)
  FROM purchase_order o, product p
 WHERE o.id = l.order_id AND p.id = l.productid
   AND o.status <> 'CONCEPT'
   AND l.extraunitcost IS NULL
   AND (o.supplierid IS NULL OR o.supplierid = p.supplierid
        OR NOT EXISTS (SELECT 1 FROM product_supplier s
                        WHERE s.product_id = p.id AND s.supplier_id = o.supplierid AND s.created_at <> now()));

UPDATE purchase_order_line l
   SET exwprice = p.exwprice, exwcurrency = coalesce(p.exwcurrency, 'USD')
  FROM purchase_order o, product p
 WHERE o.id = l.order_id AND p.id = l.productid
   AND o.status <> 'CONCEPT'
   AND l.exwprice IS NULL AND l.exwcurrency IS NULL
   AND p.exwprice IS NOT NULL
   AND (o.supplierid IS NULL OR o.supplierid = p.supplierid
        OR NOT EXISTS (SELECT 1 FROM product_supplier s
                        WHERE s.product_id = p.id AND s.supplier_id = o.supplierid AND s.created_at <> now()));

COMMIT;
