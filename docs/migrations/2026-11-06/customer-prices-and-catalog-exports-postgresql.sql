-- Klantprijzen and the catalogue export journal (Emre, 2026-11-06).
-- customer_product_price: one agreed price per customer and product, excl. VAT on the product's own
-- sales unit (per display when sold per display) like the catalogue price, with the basis it was set
-- on (sales_unit, pieces_per_unit, unit_key) and the catalogue price of that moment;
-- customer_product_price_history: append-only, every set, change, end date and removal with its
-- source (CUSTOMER_SCREEN, CATALOG_EXPORT, CUSTOMER_DELETED);
-- catalog_export and catalog_export_line: every catalogue PDF made with prices or for a recipient
-- (who, when, for whom with the name as printed, layout, language, counts, file name, PDF sha256) and
-- per product the price it printed, the catalogue and customer price and where the printed one came
-- from (CATALOGUE, CUSTOMER, ONE_OFF, ON_REQUEST).
--
-- Additive and rerunnable: four new tables with their indexes, no existing table is touched and no
-- row is written. Units, sources and layouts are plain varchars without a CHECK constraint, and there
-- are no foreign keys (the services keep the integrity: a deleted customer's prices are removed by
-- CustomerPriceDeletionListener, its exports stay under the name they were made for). Every column
-- carries the name its entity gives it.
begin;
set local lock_timeout = '15s';

create table if not exists customer_product_price (
    id bigint generated by default as identity primary key,
    customer_id bigint not null,
    product_id bigint not null,
    price_excl_vat numeric(19,2) not null,
    sales_unit varchar(16) not null,
    pieces_per_unit integer,
    unit_key varchar(40),
    catalogue_price_eur numeric(19,2),
    valid_until date,
    note varchar(300),
    created_at timestamptz not null,
    created_by varchar(80) not null,
    updated_at timestamptz not null,
    updated_by varchar(80) not null,
    constraint uk_customer_product_price unique (customer_id, product_id)
);
create index if not exists idx_customer_product_price_product on customer_product_price (product_id);

create table if not exists customer_product_price_history (
    id bigint generated by default as identity primary key,
    customer_id bigint not null,
    product_id bigint not null,
    price_excl_vat numeric(19,2),
    previous_price_excl_vat numeric(19,2),
    sales_unit varchar(16),
    pieces_per_unit integer,
    unit_key varchar(40),
    valid_until date,
    source varchar(30) not null,
    changed_at timestamptz not null,
    changed_by varchar(80) not null
);
create index if not exists idx_customer_price_history
    on customer_product_price_history (customer_id, product_id, changed_at);

create table if not exists catalog_export (
    id bigint generated by default as identity primary key,
    exported_at timestamptz not null,
    exported_by varchar(80) not null,
    exported_by_name varchar(100),
    customer_id bigint,
    customer_name varchar(255),
    layout varchar(16) not null,
    language varchar(4) not null,
    include_prices boolean not null,
    prices_valid_until date,
    product_count integer not null,
    customer_price_count integer not null,
    one_off_count integer not null,
    on_request_count integer not null,
    file_name varchar(160) not null,
    pdf_bytes bigint not null,
    pdf_sha256 varchar(64) not null
);
create index if not exists idx_catalog_export_customer on catalog_export (customer_id, exported_at);

create table if not exists catalog_export_line (
    id bigint generated by default as identity primary key,
    export_id bigint not null,
    position integer not null,
    product_id bigint not null,
    sku varchar(255),
    name varchar(255),
    sales_unit varchar(16),
    pieces_per_unit integer,
    unit_key varchar(40),
    catalogue_price_eur numeric(19,2),
    customer_price_eur numeric(19,2),
    printed_price_eur numeric(19,2),
    price_source varchar(16)
);
create index if not exists idx_catalog_export_line_export on catalog_export_line (export_id);
create index if not exists idx_catalog_export_line_product on catalog_export_line (product_id);

commit;
