-- Klantprijzen (Emre, 2026-11-06): one agreed price per customer and product, excl. VAT on the
-- product's own sales unit (per display when sold per display) like the catalogue price, with the
-- basis it was set on (sales_unit, pieces_per_unit, unit_key) and the catalogue price of that moment;
-- and an append-only history of every set, change, end date and removal with its source
-- (CUSTOMER_SCREEN, CATALOG_EXPORT, CUSTOMER_DELETED).
--
-- Additive and rerunnable: new tables with their indexes only, no existing table is touched and no
-- row is written. Units and sources are plain varchars without a CHECK constraint, and there are no
-- foreign keys (the services keep the integrity; a deleted customer's prices are removed by
-- CustomerPriceDeletionListener). Every column carries the name its entity gives it.
begin;
set local lock_timeout = '15s';

create table if not exists customer_product_price (
    id bigint generated by default as identity primary key,
    customer_id bigint not null,
    product_id bigint not null,
    price_excl_vat numeric(19,2) not null,
    sales_unit varchar(16) not null,
    pieces_per_unit integer,
    unit_key varchar(40),
    catalogue_price_eur numeric(19,2),
    valid_until date,
    note varchar(300),
    created_at timestamptz not null,
    created_by varchar(80) not null,
    updated_at timestamptz not null,
    updated_by varchar(80) not null,
    constraint uk_customer_product_price unique (customer_id, product_id)
);
create index if not exists idx_customer_product_price_product on customer_product_price (product_id);

create table if not exists customer_product_price_history (
    id bigint generated by default as identity primary key,
    customer_id bigint not null,
    product_id bigint not null,
    price_excl_vat numeric(19,2),
    previous_price_excl_vat numeric(19,2),
    sales_unit varchar(16),
    pieces_per_unit integer,
    unit_key varchar(40),
    valid_until date,
    source varchar(30) not null,
    changed_at timestamptz not null,
    changed_by varchar(80) not null
);
create index if not exists idx_customer_price_history
    on customer_product_price_history (customer_id, product_id, changed_at);

commit;
