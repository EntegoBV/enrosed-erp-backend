-- Website logins, 2026-11-15 (Emre: an active login read "Nog niet ingelogd"; and which customer
-- logged in when, and for how long).
--
-- customer_login_event            one row per moment a logged-in customer used the website: login,
--                                 password chosen with the link (that logs in too), a page that
--                                 restored the login or asked the customer's prices, the order page,
--                                 Mijn bestellingen, a PDF, logout. Visits and their length are
--                                 worked out from these rows. No page, product or address is kept.
--                                 history = true: the moments reconstructed below, once, from what
--                                 the login tables held before this release; they have no length.
-- customer_account.last_login_at  choosing a password with the link logs the customer in but was not
--                                 counted as a login; filled from password_set_at where it is empty.
--
-- Additive and rerunnable: one new table with its indexes; the history insert runs only while the
-- new table is empty (the first run, before the new release writes any row); the update only fills
-- empty values. Column names and types as CustomerLoginEventEntity gives them, no foreign keys.
begin;
set local lock_timeout = '15s';

create table if not exists customer_login_event (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    customer_id bigint not null,
    session_id bigint,
    occurred_at timestamptz not null,
    kind varchar(16) not null,
    device varchar(12),
    history boolean not null default false
);
create index if not exists idx_customer_login_event_occurred on customer_login_event (occurred_at);
create index if not exists idx_customer_login_event_account on customer_login_event (account_id, occurred_at);

-- Before the update below: a last login equal to the moment the password was chosen is that activation.
insert into customer_login_event (account_id, customer_id, session_id, occurred_at, kind, device, history)
select h.account_id, h.customer_id, h.session_id, h.occurred_at, h.kind, null, true
  from (
        -- every password chosen with the link, from the activity log (its login by e-mail address);
        -- only for a customer that still exists (a deleted customer took its login along) and only
        -- once the present login row existed (never an earlier, deleted login with the same address)
        select a.id as account_id, cast(l.entity_id as bigint) as customer_id, cast(null as bigint) as session_id,
               l.occurred_at as occurred_at, 'ACTIVATION' as kind
          from activity_log l
          join customer_account a
            on a.email = lower(substring(l.summary from '^Websitelogin geactiveerd: wachtwoord gekozen \((.+)\)$'))
         where l.entity_type = 'CUSTOMER'
           and l.summary like 'Websitelogin geactiveerd: wachtwoord gekozen (%)'
           and l.entity_id ~ '^[0-9]{1,18}$'
           and exists (select 1 from customer c where c.id::text = l.entity_id)
           and l.occurred_at >= a.created_at
        union all
        -- the last login with e-mail and password, unless the login moved to another customer since
        select a.id, a.customer_id, null, a.last_login_at, 'LOGIN'
          from customer_account a
         where a.last_login_at is not null
           and a.last_login_at is distinct from a.password_set_at
           and not exists (select 1 from activity_log m
                            where m.entity_type = 'CUSTOMER'
                              and starts_with(m.summary, 'Websitelogin ' || a.email || ' verplaatst ')
                              and m.occurred_at > a.last_login_at)
        union all
        -- earlier logins with e-mail and password whose session is still on record
        select s.account_id, a.customer_id, s.id, s.created_at, 'LOGIN'
          from customer_session s
          join customer_account a on a.id = s.account_id
         where (a.last_login_at is null or abs(extract(epoch from (s.created_at - a.last_login_at))) > 2)
           and (a.password_set_at is null or abs(extract(epoch from (s.created_at - a.password_set_at))) > 2)
        union all
        -- the last moment each session on record was in use, when later than its start
        select s.account_id, a.customer_id, s.id, s.last_seen_at, 'SEEN'
          from customer_session s
          join customer_account a on a.id = s.account_id
         where s.last_seen_at > s.created_at
       ) h
 where not exists (select 1 from customer_login_event);

update customer_account
   set last_login_at = password_set_at
 where last_login_at is null
   and password_set_at is not null;

commit;
