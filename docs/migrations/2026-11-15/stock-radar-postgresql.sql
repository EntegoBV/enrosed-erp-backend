-- Voorraadradar (iPhone Duo, PS5 Pro), back on 2026-11-15 without a browser: the last
-- seen state per watched shop page and item. No business data; rerunnable.
-- The first radar's table (2026-10-28 .. 2026-11-13) is already gone on production;
-- dropping it again here keeps that cleanup in one place.
drop table if exists stock_radar_store;

create table if not exists stock_radar_watch (
    id bigint generated by default as identity primary key,
    watch_key varchar(60) not null unique,
    available boolean,
    read_available boolean,
    in_stock boolean,
    status_text varchar(300),
    delivery_by date,
    price_eur numeric(10,2),
    places varchar(2000),
    announced_places varchar(2000),
    checked_at timestamptz,
    good_at timestamptz,
    changed_at timestamptz,
    notified_at timestamptz,
    gone_reads integer,
    last_error varchar(500),
    error_count integer,
    refused boolean,
    check_count bigint,
    last_push_status integer,
    last_mail_status integer
);

-- The latest read's own verdict (added after the first deploy of 2026-11-15; rerunnable).
alter table stock_radar_watch add column if not exists read_available boolean;

-- Extra addresses that get the radar's mails too; Emre adds and removes them on the screen.
create table if not exists stock_radar_recipient (
    id bigint generated by default as identity primary key,
    email varchar(254) not null unique,
    created_at timestamptz not null default now()
);
