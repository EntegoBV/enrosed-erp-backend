-- Stock radar: last seen availability per watched shop (iPhone Duo). Additive; no business data.
create table if not exists stock_radar_store (
    id bigint generated by default as identity primary key,
    store_key varchar(40) not null unique,
    available boolean,
    in_stock boolean,
    status_text varchar(300),
    delivery_by date,
    price_eur numeric(10,2),
    found_url varchar(600),
    checked_at timestamptz,
    changed_at timestamptz,
    notified_at timestamptz,
    last_error varchar(500),
    error_count integer,
    check_count bigint,
    last_push_status integer,
    last_mail_status integer
);
