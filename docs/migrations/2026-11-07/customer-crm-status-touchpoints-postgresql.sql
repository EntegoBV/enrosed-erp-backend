-- Klantstatus and contactmomenten on the customer (Emre, 2026-11-07: the customer list as a small
-- CRM, where a customer stands and what we already did for them).
-- customer.crm_status: NIEUW, IN_GESPREK, ACTIEF, SLAPEND or VERLOREN as a plain varchar without a
-- CHECK constraint, so a status can be added without a migration. Existing customers stay null on
-- purpose: nothing is guessed from their orders, the screen reads null as "Geen status" and Emre
-- sets the status himself.
-- customer_touchpoint: one row per customer and kind of contact (GEMAILD, GEBELD, GESPROKEN,
-- CATALOGUS_GESTUURD, STAAL_GESTUURD, or another upper-case code) with when it was first ticked
-- and by whom; ticking it off deletes the row. No foreign key, like the customer prices:
-- CustomerAdapter removes the rows with the customer.
--
-- Additive and rerunnable: one nullable column, one new table with its unique constraint and
-- index, no row is written. Every column carries the name its entity gives it; done_at is
-- timestamptz like the other Instant columns. Runs after sales-line-price-source-postgresql.sql.
begin;
set local lock_timeout = '15s';

alter table customer add column if not exists crm_status varchar(24);

create table if not exists customer_touchpoint (
    id bigint generated by default as identity primary key,
    customer_id bigint not null,
    kind varchar(32) not null,
    done_at timestamptz not null,
    done_by varchar(80),
    constraint uk_customer_touchpoint_kind unique (customer_id, kind)
);
create index if not exists idx_customer_touchpoint_customer on customer_touchpoint (customer_id);

commit;
